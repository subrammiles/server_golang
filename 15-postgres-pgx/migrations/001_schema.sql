CREATE TABLE courses (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          TEXT        NOT NULL CHECK (length(title) <= 100),
    category       TEXT        NOT NULL,
    duration_hours INT         NOT NULL CHECK (duration_hours > 0),
    price          BIGINT      NOT NULL CHECK (price >= 0),
    capacity       INT         NOT NULL DEFAULT 30,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX courses_title_unique ON courses (lower(title));
CREATE INDEX courses_category ON courses (category);

CREATE TABLE students (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE
);

-- Many-to-many with FOREIGN KEYS: the database itself rejects enrolments for unknown students/courses
CREATE TABLE enrollments (
    student_id  BIGINT      NOT NULL REFERENCES students (id) ON DELETE CASCADE,
    course_id   BIGINT      NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
    enrolled_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (student_id, course_id)
);
